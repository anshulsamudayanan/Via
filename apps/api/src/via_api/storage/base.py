"""Object storage contract.

Keys are always generated by the server (see :func:`revision_object_key`) and
validated by every backend. User-supplied names are never used as keys.
Credentials stay on the server; browsers never receive them.
"""

from __future__ import annotations

import re
import uuid
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import BinaryIO

_KEY_RE = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,511}$")


class StorageError(RuntimeError):
    """Backend failure (network, permissions...). Message is safe to log, not to show users."""


class ObjectNotFoundError(StorageError):
    pass


class InvalidKeyError(ValueError):
    pass


@dataclass(frozen=True)
class ObjectInfo:
    key: str
    size_bytes: int
    content_type: str | None


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key or "//" in key or key.endswith("/"):
        raise InvalidKeyError(f"Invalid storage key: {key!r}")
    return key


def revision_object_key(project_id: uuid.UUID, revision_id: uuid.UUID, kind: str) -> str:
    """Canonical key layout: ``projects/<project>/revisions/<revision>/<kind>``."""
    if kind not in {"source", "normalized.json.gz"}:
        raise InvalidKeyError(f"Unknown object kind {kind!r}")
    return validate_key(f"projects/{project_id}/revisions/{revision_id}/{kind}")


class StorageBackend(ABC):
    name: str

    @abstractmethod
    def put(self, key: str, data: BinaryIO | bytes, *, content_type: str, size: int | None = None) -> ObjectInfo:
        """Store an object, replacing any existing one at ``key``."""

    @abstractmethod
    def get(self, key: str) -> bytes:
        """Return the full object. Raises :class:`ObjectNotFoundError`."""

    @abstractmethod
    def stat(self, key: str) -> ObjectInfo:
        """Return metadata. Raises :class:`ObjectNotFoundError`."""

    @abstractmethod
    def delete(self, key: str) -> None:
        """Delete an object; deleting a missing object is not an error."""

    @abstractmethod
    def check(self) -> None:
        """Verify the backend is reachable and usable. Raises :class:`StorageError`."""

    def exists(self, key: str) -> bool:
        try:
            self.stat(key)
        except ObjectNotFoundError:
            return False
        return True
